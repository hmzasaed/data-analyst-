"""Markdown renderer.

Small, dependency-free and deterministic. The renderer never adds a number; it only
formats the `ReportDocument` that the composer produced.
"""

from __future__ import annotations

from insightflow_contracts import ArtifactRef, ReportDocument, ReportTable


def render_markdown(
    document: ReportDocument,
    *,
    charts: list[ArtifactRef] | None = None,
    tables: list[ArtifactRef] | None = None,
) -> str:
    """Render a report to Markdown."""
    lines: list[str] = [f"# {document.title}", ""]

    if document.source_filename:
        lines.extend([f"**File:** `{document.source_filename}`", ""])
    if document.objective:
        lines.extend([f"**Objective:** {document.objective}", ""])
    if document.is_exploratory:
        lines.extend(
            [
                "> This is an **exploratory** report: the user did not ask a specific "
                "question, so the analysis is general and not targeted at a decision.",
                "",
            ]
        )
    if document.kpis:
        lines.append("| " + " | ".join(kpi.label for kpi in document.kpis) + " |")
        lines.append("| " + " | ".join("---" for _ in document.kpis) + " |")
        lines.append("| " + " | ".join(kpi.value for kpi in document.kpis) + " |")
        lines.append("")

    sections = document.ordered_sections()
    lines.extend(["## Contents", ""])
    lines.extend(f"{index}. {section.heading}" for index, section in enumerate(sections, start=1))
    lines.append("")

    placed: set[str] = set()
    for index, section in enumerate(sections, start=1):
        lines.extend([f"## {index}. {section.heading}", ""])
        body = section.body_markdown.strip()
        if body:
            lines.extend([body, ""])
        if section.warnings:
            lines.extend(["> **Warnings**"])
            lines.extend(f"> - {warning}" for warning in section.warnings)
            lines.append("")
        for table in section.tables:
            lines.extend(_table(table))
        for chart in section.charts:
            placed.add(chart.artifact_id)
            lines.append(f"![{chart.title}](charts/{chart.artifact_id}.png)")
            lines.append("")
            lines.append(f"*{chart.title}.* {chart.caption or ''}".strip())
            lines.append("")
        footer = section.footer_markdown.strip()
        if footer:
            lines.extend([footer, ""])

    # As in the HTML: only documents that place no charts list them all here.
    loose = [] if placed else list(charts or [])
    if loose:
        lines.extend(["## Additional charts", ""])
        for chart in loose:
            lines.append(f"- `{chart.artifact_id}` - {chart.mime_type or 'image'} "
                         f"({chart.byte_size or 0:,} bytes)")
        lines.append("")

    if tables:
        lines.extend(["## Appendix: evidence tables", ""])
        lines.append("| Artifact | Rows |")
        lines.append("| --- | --- |")
        for table in tables:
            lines.append(f"| `{table.artifact_id}` | {table.row_count or 0:,} |")
        lines.append("")

    lines.extend(
        [
            "---",
            "",
            "Generated by InsightFlow. Every figure above was computed by a registered "
            "analysis tool and stored as an artifact; no number in this report was produced "
            "by a language model.",
        ]
    )
    return "\n".join(lines).strip() + "\n"


def _table(table: ReportTable) -> list[str]:
    def cell(value: str) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    out = [f"### {table.title}", ""]
    out.append("| " + " | ".join(cell(c) for c in table.columns) + " |")
    out.append("| " + " | ".join(
        "---:" if index in table.numeric_columns else "---" for index in range(len(table.columns))
    ) + " |")
    out.extend("| " + " | ".join(cell(c) for c in row) + " |" for row in table.rows)
    out.append("")
    meta = " ".join(filter(None, [
        table.note,
        f"Source: `{table.source_artifact_id}.csv`." if table.source_artifact_id else None,
    ]))
    if meta:
        out.extend([f"_{meta}_", ""])
    return out
